"""Writes src/lib/imageLibrary.ts from config/images.yaml (the checked Commons catalog).

    python3 scripts/build_image_library.py

The catalog's own rules (license list, credit fields) are validated by scripts/validate_config.py;
this only copies the fields the page needs. Each image's country comes from its `country` field
or, for city images, from the cities it covers.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOG = ROOT / "config" / "images.yaml"
OUT = ROOT / "frontend" / "src" / "lib" / "imageLibrary.ts"

# GeoNames ids of the catalog's cities, by country (from config/cities.csv).
def city_countries():
    out = {}
    for line in (ROOT / "config" / "cities.csv").read_text().splitlines()[1:]:
        cells = line.split(",")
        if len(cells) > 3 and cells[0].isdigit():
            out[int(cells[0])] = cells
    return out


def value(raw):
    raw = re.sub(r"\s+#.*$", "", raw.strip()) if not raw.strip().startswith('"') else raw.strip()
    if raw.startswith('"'):
        return raw[1 : raw.index('"', 1)]
    if raw.startswith("["):
        return [v.strip().strip("'\"") for v in raw[1:-1].split(",") if v.strip()]
    return raw


def entries():
    current = None
    for line in CATALOG.read_text().splitlines():
        if line.startswith("  - id:"):
            if current:
                yield current
            current = {"id": value(line.split(":", 1)[1])}
        elif current is not None and re.match(r"^    [a-z_]+:", line):
            key, raw = line.strip().split(":", 1)
            current[key] = value(raw)
    if current:
        yield current


def main():
    header = (ROOT / "config" / "cities.csv").read_text().splitlines()[0].split(",")
    cities = city_countries()
    id_col, country_col = header.index(next(h for h in header if h in ("geonames_id", "id"))), header.index(
        next(h for h in header if h in ("country", "country_iso2", "iso2"))
    )
    images = []
    for e in entries():
        ids = [int(c) for c in e.get("cities", [])]
        country = e.get("country") or next((cities[i][country_col] for i in ids if i in cities), None)
        images.append(
            {
                "id": e["id"],
                "url": e["image_url"],
                "filePage": e["file_page"],
                "creator": e["creator"],
                "credit": e["attribution"],
                "license": e["license"],
                "licenseUrl": e.get("license_url", ""),
                "alt": e["alt"],
                "caption": e["caption"],
                "position": e.get("position", "50% 50%"),
                "country": country,
                "cities": ids,
                "sectors": e.get("sectors", []),
            }
        )
    body = json.dumps(images, indent=2, ensure_ascii=False)
    OUT.write_text(
        "/**\n"
        " * Every checked Wikimedia Commons file in config/images.yaml, for card thumbnails and heroes.\n"
        " * Generated by scripts/build_image_library.py; do not edit by hand. Each file's page was read\n"
        " * (creator, license); each shows a place or subject, never a news event, and is labelled.\n"
        " */\n"
        "export interface LibraryImage {\n"
        "  id: string\n"
        "  /** Wikimedia thumbnail URL with {width}: 500, 960 or 1920. */\n"
        "  url: string\n"
        "  filePage: string\n"
        "  creator: string\n"
        "  credit: string\n"
        "  license: string\n"
        "  licenseUrl: string\n"
        "  alt: string\n"
        "  caption: string\n"
        "  position: string\n"
        "  country: string | null\n"
        "  cities: number[]\n"
        "  sectors: string[]\n"
        "}\n\n"
        f"export const IMAGE_LIBRARY: LibraryImage[] = {body}\n"
    )
    print(f"{len(images)} images -> {OUT.relative_to(ROOT)}")


main()
